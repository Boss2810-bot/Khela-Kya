async function seed() {
  try {
    await connectDB();
    console.log('[Seed] Connected to MongoDB');

    // Clear existing turfs
    const deleted = await Turf.deleteMany({});
    console.log(`[Seed] Cleared ${deleted.deletedCount} existing turf(s)`);

    // Insert sample turfs
    const inserted = await Turf.insertMany(SAMPLE_TURFS);
    console.log(`[Seed] Inserted ${inserted.length} turf(s)`);

    inserted.forEach((t) => console.log(`  ✓ ${t.turfName} — ${t.city}`));
  } catch (err) {
    console.error('[Seed] Error:', err.message);
    process.exit(1);
  } finally {
    await disconnectDB();
    console.log('[Seed] Done.');
  }
}

seed();
